"""Generate a minimal OCCT 7.9.1 CMake package for the robot3d toolkit closure.

This adapter only describes pinned official SDK binaries. It does not modify OCCT
headers, libraries, runtime binaries, or the official SDK's full CMake package.
Run after installing matching DLLs and import libraries for the configuration.
"""
import argparse
import json
import os
import pathlib
import runpy
import sys

VERSION = '7.9.1'
SOURCE_COMMIT = '36c80dbe7b199348e2f0a2d6932a462a37fd0b90'
ROOT_TOOLKITS = ('TKDESTEP', 'TKDEIGES', 'TKMesh', 'TKXCAF', 'TKPrim')
OFFICIAL_ASSETS = {'Release': 257073667, 'Debug': 257073722}


def file_index(folder, extension):
    if not folder.is_dir():
        raise RuntimeError('Required SDK directory is missing: ' + str(folder))
    result = {}
    for name in os.listdir(str(folder)):
        if name.lower().endswith(extension) and (folder / name).is_file():
            key = name.lower()
            if key in result:
                raise RuntimeError('Ambiguous case-insensitive SDK filename: ' + name)
            result[key] = folder / name
    return result


def toolkit_closure(sdk, imports):
    release_dlls = file_index(sdk / 'win64' / 'vc14' / 'bin', '.dll')
    pending = [name + '.dll' for name in ROOT_TOOLKITS]
    dependencies = {}
    dll_paths = {}
    while pending:
        requested = pending.pop(0)
        key = requested.lower()
        if key in dll_paths:
            continue
        path = release_dlls.get(key)
        if path is None:
            raise RuntimeError('Release DLL required to inspect toolkit closure is missing: ' + requested)
        direct = []
        for imported in imports(str(path)):
            if imported.lower().startswith('tk') and imported.lower().endswith('.dll'):
                dependency = release_dlls.get(imported.lower())
                if dependency is None:
                    raise RuntimeError(str(path) + ' imports missing toolkit ' + imported)
                direct.append(dependency.stem)
                pending.append(dependency.name)
        dll_paths[key] = path
        dependencies[path.stem] = sorted(set(direct), key=str.lower)
    return dict(sorted(dependencies.items(), key=lambda item: item[0].lower()))


def cmake_quote(value):
    if any(c in value for c in (';', '\n', '\r', '$', '"')):
        raise RuntimeError('Cannot safely represent value in generated CMake: ' + value)
    return '"' + value.replace('\\', '/') + '"'


def generated_config(configuration, dependencies, binary_names, library_names):
    binary_folder = 'bind' if configuration == 'Debug' else 'bin'
    library_folder = 'libd' if configuration == 'Debug' else 'lib'
    upper = configuration.upper()
    lines = [
        '# Generated by robot3d tools/configure-occt-official-sdk.py.',
        '# Official OCCT 7.9.1 toolkit dependency adapter; no OCCT code is modified.',
        'get_filename_component(OpenCASCADE_INSTALL_PREFIX "${CMAKE_CURRENT_LIST_DIR}/.." ABSOLUTE)',
        'set(OpenCASCADE_VERSION "7.9.1")',
        'set(OpenCASCADE_MAJOR_VERSION "7")',
        'set(OpenCASCADE_MINOR_VERSION "9")',
        'set(OpenCASCADE_MAINTENANCE_VERSION "1")',
        'set(OpenCASCADE_DEVELOPMENT_VERSION "")',
        'set(OpenCASCADE_SOURCE_COMMIT "' + SOURCE_COMMIT + '")',
        'set(OpenCASCADE_COMPILER "vc14")',
        'set(OpenCASCADE_BUILD_SHARED_LIBS ON)',
        'set(OpenCASCADE_BUILD_WITH_DEBUG ' + ('TRUE' if configuration == 'Debug' else 'FALSE') + ')',
        'set(OpenCASCADE_INCLUDE_DIR "${OpenCASCADE_INSTALL_PREFIX}/inc")',
        'set(OpenCASCADE_BINARY_DIR "${OpenCASCADE_INSTALL_PREFIX}/win64/vc14/' + binary_folder + '")',
        'set(OpenCASCADE_LIBRARY_DIR "${OpenCASCADE_INSTALL_PREFIX}/win64/vc14/' + library_folder + '")',
        'set(OpenCASCADE_RESOURCE_DIR "${OpenCASCADE_INSTALL_PREFIX}/src")',
        'set(OpenCASCADE_SCRIPT_DIR "${OpenCASCADE_INSTALL_PREFIX}")',
        'set(OpenCASCADE_INCLUDE_DIRS "${OpenCASCADE_INCLUDE_DIR}")',
        'set(OpenCASCADE_LIBRARY_DIRS "${OpenCASCADE_LIBRARY_DIR}")',
        'set(OpenCASCADE_LIBRARIES "' + ';'.join(dependencies) + '")',
        'set(OpenCASCADE_FOUND TRUE)',
        'set(ROBOT3D_OCCT_GENERATED_TOOLKIT_CONFIG TRUE)',
        '',
    ]
    for target, direct in dependencies.items():
        lines.extend([
            'if(NOT TARGET ' + target + ')',
            '  add_library(' + target + ' SHARED IMPORTED GLOBAL)',
            '  set_target_properties(' + target + ' PROPERTIES',
            '    IMPORTED_CONFIGURATIONS "' + upper + '"',
            '    IMPORTED_LOCATION "${OpenCASCADE_BINARY_DIR}/' + binary_names[target] + '"',
            '    IMPORTED_IMPLIB "${OpenCASCADE_LIBRARY_DIR}/' + library_names[target] + '"',
            '    IMPORTED_LOCATION_' + upper + ' "${OpenCASCADE_BINARY_DIR}/' + binary_names[target] + '"',
            '    IMPORTED_IMPLIB_' + upper + ' "${OpenCASCADE_LIBRARY_DIR}/' + library_names[target] + '"',
            '    INTERFACE_INCLUDE_DIRECTORIES "${OpenCASCADE_INCLUDE_DIR}"',
            '    INTERFACE_LINK_LIBRARIES "' + ';'.join(direct) + '"',
            '  )',
            'endif()',
        ])
    lines.append('')
    return '\n'.join(lines)


def generated_version():
    return '''# Generated exact-version package check for the pinned official SDK.
set(PACKAGE_VERSION "7.9.1")
if(PACKAGE_FIND_VERSION STREQUAL PACKAGE_VERSION)
  set(PACKAGE_VERSION_EXACT TRUE)
  set(PACKAGE_VERSION_COMPATIBLE TRUE)
else()
  set(PACKAGE_VERSION_COMPATIBLE FALSE)
endif()
if(CMAKE_SIZEOF_VOID_P AND NOT CMAKE_SIZEOF_VOID_P EQUAL 8)
  set(PACKAGE_VERSION_UNSUITABLE TRUE)
endif()
'''


def write_verified(path, text):
    original = path.read_bytes() if path.is_file() else b''
    encoding = 'utf-8-sig' if original.startswith(b'\xef\xbb\xbf') else 'utf-8'
    # Preserve existing newline convention; generated new files use CRLF.
    if original:
        with open(str(path), 'r', encoding=encoding, newline='') as stream:
            old_text = stream.read()
        newline = '\r\n' if '\r\n' in old_text else '\n'
    else:
        newline = '\r\n'
    normalized = text.replace('\r\n', '\n').replace('\r', '\n').replace('\n', newline)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(str(path), 'w', encoding=encoding, newline='') as stream:
        stream.write(normalized)
    expected = normalized.encode(encoding)
    actual = path.read_bytes()
    if actual != expected:
        raise RuntimeError('Read-back verification failed: ' + str(path))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('sdk', help='Official occt_vc14-64 SDK root')
    parser.add_argument('--configuration', choices=('Release', 'Debug'), default='Release')
    parser.add_argument('--metadata', help='Override build/deps/occt-sdk-<configuration>.json')
    parser.add_argument('--dry-run', action='store_true', help='Validate files and print the closure without writing')
    args = parser.parse_args()
    sdk = pathlib.Path(args.sdk).resolve()
    script_root = pathlib.Path(__file__).resolve().parent
    imports = runpy.run_path(str(script_root / 'fetch-occt-sdk-runtime.py'))['imports']
    if not (sdk / 'inc' / 'Standard_Version.hxx').is_file():
        raise RuntimeError('OCCT headers are missing: ' + str(sdk / 'inc'))
    if not (sdk / 'src').is_dir():
        raise RuntimeError('OCCT runtime resources are missing: ' + str(sdk / 'src'))
    dependencies = toolkit_closure(sdk, imports)
    config = args.configuration
    dlls = file_index(sdk / 'win64' / 'vc14' / ('bind' if config == 'Debug' else 'bin'), '.dll')
    libs = file_index(sdk / 'win64' / 'vc14' / ('libd' if config == 'Debug' else 'lib'), '.lib')
    binary_names, library_names, missing = {}, {}, []
    for target in dependencies:
        dll = dlls.get((target + '.dll').lower())
        lib = libs.get((target + '.lib').lower())
        if dll is None:
            missing.append(target + '.dll')
        else:
            binary_names[target] = dll.name
        if lib is None:
            missing.append(target + '.lib')
        else:
            library_names[target] = lib.name
    if missing:
        raise RuntimeError(config + ' SDK is incomplete; install matching files first: ' + ', '.join(missing))
    print(config + ' toolkit closure (' + str(len(dependencies)) + '): ' + ', '.join(dependencies))
    if args.dry_run:
        print('Dry run: required DLLs/import libraries exist; no files were written.')
        return
    output = sdk / ('robot3d-cmake-' + config)
    metadata = pathlib.Path(args.metadata).resolve() if args.metadata else (
        script_root.parent / 'build' / 'deps' / ('occt-sdk-' + config + '.json'))
    record = {}
    if metadata.is_file():
        with open(str(metadata), 'r', encoding='utf-8-sig', newline='') as stream:
            previous = json.load(stream)
        if os.path.normcase(os.path.abspath(previous.get('prefix', ''))) == os.path.normcase(str(sdk)):
            record.update(previous)
    record.update({
        'version': VERSION,
        'sourceCommit': SOURCE_COMMIT,
        'provenance': 'official-prebuilt-vc14-' + config.lower(),
        'configuration': config,
        'occtDir': str(output),
        'prefix': str(sdk),
        'officialAssetId': OFFICIAL_ASSETS[config],
        'generatedToolkitConfig': True,
        'rootToolkits': list(ROOT_TOOLKITS),
        'toolkitClosure': list(dependencies),
        'adapter': 'tools/configure-occt-official-sdk.py',
    })
    write_verified(output / 'OpenCASCADEConfig.cmake',
                   generated_config(config, dependencies, binary_names, library_names))
    write_verified(output / 'OpenCASCADEConfigVersion.cmake', generated_version())
    write_verified(metadata, json.dumps(record, ensure_ascii=False, indent=2) + '\n')
    print('Generated toolkit package: ' + str(output))
    print('SDK metadata: ' + str(metadata))


if __name__ == '__main__':
    try:
        main()
    except Exception as error:
        print('OCCT SDK configuration failed: ' + str(error), file=sys.stderr)
        sys.exit(1)
